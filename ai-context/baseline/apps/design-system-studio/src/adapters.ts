import { resolveTheme, type StudioData, type Theme } from './types';

export type Platform = 'web' | 'flutter' | 'compose' | 'swiftui';

function entries(theme: Theme) {
  return Object.entries(theme.tokens).flatMap(([group, tokens]) => (
    Object.entries(tokens).map(([name, value]) => ({ group, name, value, key: `${group}-${name}` }))
  ));
}

function identifier(value: string) {
  return value.replace(/[^a-zA-Z0-9]+(.)/g, (_, character: string) => character.toUpperCase()).replace(/^[0-9]/, '_$&');
}

function quoted(value: string) {
  return JSON.stringify(value);
}

export function exportStudio(studio: StudioData, platform: Platform) {
  const theme = resolveTheme(studio, studio.tokens.themes[0]?.id || 'default');
  const tokens = entries(theme);
  const packageName = studio.adapterSettings.packageName || 'design_system';
  const prefix = studio.adapterSettings.webPrefix || 'ds';

  if (platform === 'web') {
    const variables = tokens.map(({ key, value }) => `  --${prefix}-${key}: ${value};`).join('\n');
    return {
      filename: `${prefix}-tokens.css`,
      content: `/* Generated by AIC Design System Studio. */\n:root {\n${variables}\n}\n`,
      language: 'CSS',
    };
  }
  if (platform === 'flutter') {
    const values = tokens.map(({ key, value }) => `  static const String ${identifier(key)} = ${quoted(value)};`).join('\n');
    return {
      filename: `${packageName}_tokens.dart`,
      content: `// Generated proof-of-concept token adapter.\nabstract final class DesignTokens {\n${values}\n}\n`,
      language: 'Dart',
    };
  }
  if (platform === 'compose') {
    const values = tokens.map(({ key, value }) => `  const val ${identifier(key)} = ${quoted(value)}`).join('\n');
    return {
      filename: 'DesignTokens.kt',
      content: `// Generated proof-of-concept token adapter.\npackage ${packageName}\n\nobject DesignTokens {\n${values}\n}\n`,
      language: 'Kotlin',
    };
  }
  const values = tokens.map(({ key, value }) => `  static let ${identifier(key)} = ${quoted(value)}`).join('\n');
  return {
    filename: 'DesignTokens.swift',
    content: `// Generated proof-of-concept token adapter.\nimport SwiftUI\n\nenum DesignTokens {\n${values}\n}\n`,
    language: 'Swift',
  };
}

